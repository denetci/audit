const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const context = {window: {}, cancelAnimationFrame() {}, requestAnimationFrame() { return 1; }};
vm.createContext(context);
vm.runInContext(fs.readFileSync('static/audit-map.js', 'utf8'), context);
const map = Object.create(context.window.AuditMap.prototype);
const node = (id, x, tx) => ({ id, x, y: 200, tx, ty: 200, vx: 0, vy: 0, radius: 50, el: { offsetWidth: 100, offsetHeight: 100, style: {} } });
Object.assign(map, {branch: 'Mali', host: {clientWidth: 800}, stage: {clientWidth: 800, clientHeight: 600}, nodes: [node('a', 250, 200)], edges: [], cache: new Map(), reduced: {matches: false}});
map.animate();
assert.ok(map.nodes[0].x < 250 && map.nodes[0].x > 200, 'Node should spring toward anchor rather than snap');
map.nodes = [node('a', 250, 250), node('b', 300, 300)];
map.animate();
assert.ok(map.nodes[0].x < 250 && map.nodes[1].x > 300, 'Overlapping circles should repel');
map.dragging = map.nodes[0];
const heldX = map.dragging.x;
map.animate();
assert.equal(map.dragging.x, heldX, 'Pointer-held circle must stay under pointer');
map.dragging = null;
map.reduced.matches = true;
map.nodes = [node('a', 250, 200)];
map.animate();
assert.equal(map.nodes[0].x, 200, 'Reduced motion remains respected');
console.log('PASS: elastic motion, collision response, drag position and reduced motion');
