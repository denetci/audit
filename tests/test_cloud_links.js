const fs = require('fs'), vm = require('vm'), assert = require('assert');
const source = fs.readFileSync('static/script.js', 'utf8');
const opened = [], alerts = [];
const context = { URL, prompt: () => '2', alert: value => alerts.push(value), window: {open: (...args) => opened.push(args)} };
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function normalizeCloudUrl('), source.indexOf('function chooseAndDownloadDocument(')), context);
assert.equal(context.validateCloudUrls('https://example.com/a'), 'https://example.com/a');
assert.equal(context.validateCloudUrls(' example.com/a\r\nhttps://example.com/b\n\nhttps://example.com/b '), 'https://example.com/a\nhttps://example.com/b');
assert.equal(context.validateCloudUrls(''), '');
assert.throws(() => context.validateCloudUrls('https://'));
assert.throws(() => context.validateCloudUrls('file:///test'));
const list = { items: [], replaceChildren() { this.items = []; }, append(item) { this.items.push(item); } };
const dialog = { open: false, querySelector: () => list, showModal() { this.open = true; } };
context.document = { querySelector: () => dialog, createElement: () => ({}) };
context.escapeHtml = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;');
context.openCloudUrl('https://example.com/a');
assert.equal(opened[0][0], 'https://example.com/a');
context.openCloudUrl('https://example.com/a\nhttps://example.com/b');
assert.equal(opened.length, 1);
assert.equal(dialog.open, true);
assert.equal(list.items.length, 2);
assert.equal(list.items[1].href, 'https://example.com/b');
assert.equal(list.items[1].target, '_blank');
assert.equal(list.items[1].rel, 'noopener noreferrer');
assert.equal(context.getCloudLinkLabel('https://example.com/files/481?dir=/Arsiv/2026/Program%20Oluru').title, 'Program Oluru');
context.openCloudUrl('https://example.com/c\nhttps://example.com/d');
assert.equal(list.items.length, 2);
assert.equal(list.items[0].href, 'https://example.com/c');
assert.ok(!source.slice(source.indexOf('function openCloudUrl('), source.indexOf('function chooseAndDownloadDocument(')).includes('prompt('));
console.log('PASS: legacy links, validation, readable labels, clickable picker, refresh and direct single-link opening.');
